#!/usr/bin/env node
/**
 * Regenerates src/lib/migrations/registry.ts from supabase/migrations/*.sql.
 *
 * The registry inlines the SQL rather than reading the directory at runtime,
 * because only imported files are bundled into a serverless function — a
 * filesystem read works locally and returns nothing in production. That is
 * correct and stays. What was not correct is that the file was maintained by
 * hand, so it stopped at 044 while 045–048 sat in the repo unrunnable from the
 * phone, which is the only place they were ever going to be run from.
 *
 * Usage: npm run migrations:registry
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MIGRATIONS_DIR = "supabase/migrations";
const OUT = "src/lib/migrations/registry.ts";

/**
 * Not offered in the panel.
 *
 * 001–033 predate the runner and were applied by hand; 037 creates exec_sql and
 * applied_migrations, so it is the one that cannot be applied by the thing it
 * bootstraps.
 */
const EXCLUDED = (id) => {
  const n = Number(id.slice(0, 3));
  return n <= 33 || n === 37;
};

/**
 * Hand-written where the file's own first line is not a good button label.
 * Anything absent falls back to the first real comment line of the SQL.
 */
const DESCRIPTIONS = {
  "034_dedupe_chargers_by_site": "Dedupe helper functions (defines only; run the dedupe separately)",
  "035_debug_stats_functions": "Aggregate helpers this debug panel reads",
  "036_upsert_dedupe_source_refs": "Guard the batch upsert against a repeated source ref",
  "038_dedupe_same_site_across_operator_names": "Collapse one site stored under several operator names",
  "039_dedupe_same_site_brand": "Collapse one site whose brand is split across name and operator",
  "040_saved_routes_unique": "One saved route per origin/destination pair (removes existing duplicates)",
  "041_dedupe_use_spatial_index": "Fix the dedupe statement timeout (381s -> 0.2s); apply before running dedupe",
  "042_charger_sources_fk_index": "Index the charger_sources foreign key (cascade delete 1716ms -> 25ms)",
  "043_dedupe_keeps_provenance": "Dedupe transfers source refs to the survivor; recompute source_count",
  "044_charger_query_limits": "Stop silently dropping stations from map queries (500 cap -> 2000)",
  "045_push_subscription_ownership":
    "Push endpoints are owned per user — posting someone else's no longer steals their row",
  "046_email_verification":
    "profiles.email_verified_at — needs RESEND_API_KEY set, or document recovery locks for everyone",
  "047_revoke_function_execute_from_anon":
    "Revoke function EXECUTE from anon/authenticated (read its header first)",
  "048_enable_rls_everywhere":
    "RLS sweep — expected to change nothing today; run in the SQL editor to read its NOTICE output",
};

/** First comment line that is not just the filename. */
function deriveDescription(sql, id) {
  for (const raw of sql.split("\n")) {
    const line = raw.trim();
    if (!line.startsWith("--")) continue;
    const text = line.replace(/^--+\s?/, "").trim();
    if (!text || text.startsWith("=") || text.startsWith(id)) continue;
    return text.replace(/\s+/g, " ").slice(0, 120);
  }
  return id;
}

const files = readdirSync(MIGRATIONS_DIR)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const migrations = [];
for (const file of files) {
  const id = file.replace(/\.sql$/, "");
  if (EXCLUDED(id)) continue;
  const sql = readFileSync(join(MIGRATIONS_DIR, file), "utf8");
  migrations.push({
    id,
    description: DESCRIPTIONS[id] ?? deriveDescription(sql, id),
    sql,
  });
}

const header = `// Migrations the debug panel may apply.
//
// GENERATED by scripts/generate-migration-registry.mjs — run
// \`npm run migrations:registry\` after adding a file to supabase/migrations,
// and commit the result. Editing this file by hand is what left 045–048
// unrunnable from the panel while sitting in the repo.
//
// The SQL is inlined rather than read from supabase/migrations at runtime:
// only imported files are bundled, so a filesystem read would work in
// development and return nothing in production.
//
// The apply route accepts an id from this list and nothing else — no statement
// from a client ever reaches exec_sql. Adding a migration here is a deliberate,
// reviewed act, and the review happens on the .sql file.
//
// 001-033 predate the runner and were applied by hand. 037 bootstraps exec_sql
// and applied_migrations, so it cannot be applied by the runner it creates.

export interface Migration {
  id: string;
  description: string;
  sql: string;
}

export const MIGRATIONS: Migration[] = ${JSON.stringify(migrations, null, 2)};

export function findMigration(id: string): Migration | null {
  return MIGRATIONS.find((m) => m.id === id) ?? null;
}
`;

writeFileSync(OUT, header);
console.log(`${OUT}: ${migrations.length} migrations (${migrations[0].id} … ${migrations[migrations.length - 1].id})`);
